@Composable
fun ColorSwatchDot(
    hexColor: String,
    modifier: Modifier = Modifier,
    sizeDp: Int = 18
) {
    val parsedColor = parseComposeColor(hexColor)
    Box(
        modifier = modifier
            .size(sizeDp.dp)
            .clip(CircleShape)
            .background(parsedColor)
            .border(1.dp, MaterialTheme.colorScheme.outline, CircleShape)
    )
}

fun parseComposeColor(hex: String): Color {
    return try {
        val clean = hex.trim().removePrefix("#")
        val value = clean.toLong(16)
        when (clean.length) {
            6 -> Color(0xFF000000L or value)
            8 -> Color(value)
            else -> Color(0xFFD8CFC2)
        }
    } catch (_: Exception) {
        Color(0xFFD8CFC2)
    }
}

